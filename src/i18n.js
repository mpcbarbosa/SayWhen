const DICT = { pt, es, en };

export function L(lang) {
  return DICT[lang] || DICT.pt;
}

export function t(lang, key, vars) {
  let s = L(lang)[key];
  if (typeof s !== "string") return key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(vars[k]);
  return s;
}
